test('calculator and split view resize keep both panes away from the hinge', async ({ page }) => {
  await page.goto('/'); await openApp(page, 'Safari')
  await page.getByRole('button', { name: 'Multitasking options for Safari' }).click()
  await page.getByRole('button', { name: 'Open in Split View' }).click()
  await page.getByRole('button', { name: 'Calculator', exact: true }).click()
  await expect(page.locator('.app-window')).toHaveCount(2)
  for (const name of ['7', '×', '8', 'Equals']) await page.locator('.calculator-app').getByRole('button', { name, exact: true }).click()
  await expect(page.getByLabel('Calculator result')).toHaveText('56')
  const slider = page.getByLabel('Resize split view'); await slider.focus(); await slider.press('End'); await expect(slider).toHaveValue('53')
  const bounds = await page.locator('.device-screen').boundingBox(); const reserved = await page.locator('.split-reserved').boundingBox()
  expect(bounds).not.toBeNull(); expect(reserved).not.toBeNull()
  const seam = bounds!.x + bounds!.width / 2
  expect(reserved!.x).toBeLessThanOrEqual(seam); expect(reserved!.x + reserved!.width).toBeGreaterThanOrEqual(seam)
  await page.getByRole('button', { name: 'Save app pair' }).click(); await expect(page.getByText('Saved', { exact: true })).toBeVisible()
  await pose(page, 'Closed').click(); await expect(page.locator('.app-window')).toHaveCount(1)
  await pose(page, 'Open').click(); await expect(page.locator('.app-window')).toHaveCount(2)
  await page.getByRole('button', { name: 'Close Calculator' }).click(); await expect(page.locator('.app-window')).toHaveCount(1)
  await home(page); await expect(page.locator('.home-screen')).toBeVisible()
})

