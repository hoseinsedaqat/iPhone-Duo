import { expect, test, type Page } from '@playwright/test'

const pose = (page: Page, name: string) => page.locator('.pose-button').filter({ hasText: name })
async function openApp(page: Page, name: string) { await page.getByRole('button', { name: `Open ${name}`, exact: true }).click() }
async function home(page: Page) { await page.getByRole('button', { name: 'Go Home', exact: true }).click() }

test('home, device poses, orientation and lock screen work without critical errors', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await expect(page.locator('.home-screen')).toBeVisible()
  await expect(page.locator('[data-testid="device-frame"]')).toHaveAttribute('data-mode', 'open')
  await pose(page, 'Closed').click(); await expect(page.locator('[data-testid="device-frame"]')).toHaveAttribute('data-mode', 'closed')
  await pose(page, 'Partially folded').click(); await expect(page.locator('[data-testid="device-frame"]')).toHaveAttribute('data-mode', 'partial')
  await pose(page, 'Tabletop').click(); await expect(page.locator('[data-testid="device-frame"]')).toHaveAttribute('data-mode', 'tabletop')
  await page.getByRole('button', { name: 'Landscape', exact: true }).click(); await expect(page.locator('.device-frame')).toHaveClass(/landscape/)
  await pose(page, 'Open').click(); await expect(page.locator('.device-frame')).toHaveAttribute('data-mode', 'open')
  await page.getByRole('button', { name: 'Lock screen', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Swipe up or click to unlock' })).toBeVisible()
  await page.getByRole('button', { name: 'Swipe up or click to unlock' }).click()
  await expect(page.locator('.home-screen')).toBeVisible()
  expect(errors).toEqual([])
})

